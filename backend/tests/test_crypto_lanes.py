def test_the_cbom_catalogue_covers_all_four_table_9_asset_types():
    catalogue = get_catalogue("cbom")
    scopes: set[str] = set()
    for element in catalogue.elements:
        scopes |= getattr(element.probe, "applies_to", set())

    assert {"algorithm", "protocol", "certificate"} <= scopes
    assert scopes & {"key", "related-crypto-material"}


def test_the_qbom_catalogue_anchors_the_migration_clause():
    """s.8.5.1 is what the S9 quantum-exposure rule cites."""
    assert get_catalogue("qbom").by_key("migration_strategy").clause == "8.5.1"


def test_both_lanes_are_now_implemented():
    from app.configs.laneConfig import LANE_SPECS

    assert LANE_SPECS["cbom"].implemented
    assert LANE_SPECS["qbom"].implemented


def test_each_lane_clause_sits_under_its_root():
    for lane, root in (("cbom", "8.4"), ("qbom", "8.5")):
        for element in get_catalogue(lane).elements:
            assert element.clause.startswith(root)


# --- per-asset-type scoping --------------------------------------------------


def test_an_element_is_scored_only_over_the_assets_it_applies_to():
    """Reporting a certificate as missing its cipher mode is a category error."""
    assets = [
        {"name": "c1", "asset_type": "certificate", "subject": "CN=a", "issuer": "CN=b"},
        {"name": "c2", "asset_type": "certificate", "subject": "CN=c", "issuer": "CN=d"},
        {"name": "RSA", "asset_type": "algorithm", "primitive": "signature"},
    ]
    primitive = check(get_catalogue("cbom").by_key("primitive"), assets)

    assert primitive.coverage.total == 1, "scored over algorithms only"
    assert primitive.coverage.populated == 1


def test_out_of_scope_assets_leave_the_denominator_rather_than_counting_as_populated():
    """Counting them would inflate the score until it measured document
    composition rather than declaration quality."""
    certificates_only = [{"name": f"c{index}", "asset_type": "certificate"} for index in range(10)]
    primitive = check(get_catalogue("cbom").by_key("primitive"), certificates_only)

    assert primitive.coverage.total == 0
    # An empty denominator scores 0.0, never a vacuous 100%.
    assert primitive.coverage.ratio == 0.0


def test_an_element_with_no_scope_applies_to_every_asset():
    assets = [
        {"name": "a", "asset_type": "algorithm"},
        {"name": "b", "asset_type": "certificate"},
    ]
    assert check(get_catalogue("cbom").by_key("asset_name"), assets).coverage.total == 2


