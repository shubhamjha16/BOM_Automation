def test_the_review_checklist_is_generatable():
    """S14 exits on a cryptography practitioner signing a checklist, which has
    not happened. This generates what they would review, so the encoding can be
    checked clause by clause against the published tables rather than trusted.
    """
    lines: list[str] = []
    for lane in ("cbom", "qbom"):
        catalogue = get_catalogue(lane)
        lines.append(f"{lane.upper()} — s.{catalogue.clause_root}")
        for element in catalogue.elements:
            scope = getattr(element.probe, "applies_to", None)
            lines.append(
                f"  [ ] {element.clause:<10} {element.label:<45} "
                f"{element.tier:<11} {sorted(scope) if scope else 'all assets'}"
            )

    assert len(lines) >= 30
    assert any("8.4.1.2" in line for line in lines)
    assert any("8.5.1" in line for line in lines)
