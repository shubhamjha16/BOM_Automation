async def test_rsa_with_no_migration_entry_raises_quantum_exposure():
    """The §S9 rule, now firing on a real CBOM lane rather than a fixture."""
    rsa = _asset(
        "RSA-2048",
        "algorithm",
        algorithmProperties={"primitive": "signature", "classicalSecurityLevel": 112},
    )
    summary = await run_assessment(
        org_id="org",
        submission_id="sub",
        requested_lanes=["cbom", "qbom"],
        documents=[SubmissionDocument(lane="cbom", format="CycloneDX", payload=_document([rsa]))],
    )
    findings = {item.rule_key: item for item in summary.correlation_findings}

    assert "algorithmQuantumExposure" in findings
    assert findings["algorithmQuantumExposure"].clause == "8.5.1"


async def test_a_disabled_qbom_lane_is_excluded_from_the_overall_score():
    """The §S14 exit proof: a client with no quantum hardware must not see a
    zero-scoring empty lane."""
    document = SubmissionDocument(
        lane="cbom", format="CycloneDX", payload=_document(HEALTHY_ASSETS)
    )

    enabled = await run_assessment(
        org_id="org", submission_id="a", requested_lanes=["cbom", "qbom"], documents=[document]
    )
    disabled = await run_assessment(
        org_id="org", submission_id="b", requested_lanes=["cbom"], documents=[document]
    )

    enabled_qbom = next(item for item in enabled.lane_results if item.lane == "qbom")
    disabled_qbom = next(item for item in disabled.lane_results if item.lane == "qbom")

    assert enabled_qbom.verdict is LaneVerdict.LANE_ABSENT
    assert enabled_qbom.counts_toward_overall is True

    assert disabled_qbom.verdict is LaneVerdict.LANE_NOT_APPLICABLE
    assert disabled_qbom.counts_toward_overall is False

    # The overall score is computed as though the lane did not exist.
    cbom_score = next(item for item in disabled.lane_results if item.lane == "cbom").score
    assert disabled.overall_score == cbom_score


